-- V1: core schema for the claims platform.
-- Money is NUMERIC(15,2) and is always stored with its currency. Timestamps are TIMESTAMPTZ (stored as UTC).

-- Users: claimants (policy holders) and claims staff. The id is what callers send in the X-User-Id header.
CREATE TABLE app_user (
    id     VARCHAR(20)  PRIMARY KEY,
    name   VARCHAR(100) NOT NULL,
    email  VARCHAR(255) NOT NULL,
    role   VARCHAR(20)  NOT NULL,
    team   VARCHAR(50),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT chk_app_user_role CHECK (role IN ('CLAIMANT', 'STAFF')),
    -- Only staff belong to a team.
    CONSTRAINT chk_app_user_team CHECK ((role = 'STAFF' AND team IS NOT NULL) OR (role = 'CLAIMANT' AND team IS NULL))
);

CREATE TABLE policy (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number   VARCHAR(30)    NOT NULL,
    holder_id       VARCHAR(20)    NOT NULL REFERENCES app_user (id),
    market          VARCHAR(2)     NOT NULL,
    product_type    VARCHAR(20)    NOT NULL,
    currency        VARCHAR(3)     NOT NULL,
    coverage_limit  NUMERIC(15, 2) NOT NULL,
    CONSTRAINT uq_policy_policy_number UNIQUE (policy_number),
    CONSTRAINT chk_policy_product_type CHECK (product_type IN ('MOTOR', 'PROPERTY')),
    CONSTRAINT chk_policy_coverage_limit CHECK (coverage_limit > 0),
    -- Each market has exactly one currency.
    CONSTRAINT chk_policy_market_currency CHECK ((market, currency) IN (
        ('SG', 'SGD'), ('MY', 'MYR'), ('HK', 'HKD'), ('TH', 'THB'), ('ID', 'IDR'), ('AU', 'AUD')))
);

CREATE INDEX idx_policy_holder_id ON policy (holder_id);

-- Source of the 6-digit sequence part of claim numbers (CLM-<MARKET>-<YEAR>-<SEQ>).
CREATE SEQUENCE claim_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE claim (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_number         VARCHAR(30)    NOT NULL,
    policy_id            BIGINT         NOT NULL REFERENCES policy (id),
    type                 VARCHAR(20)    NOT NULL,
    market               VARCHAR(2)     NOT NULL,
    currency             VARCHAR(3)     NOT NULL,
    incident_date        DATE           NOT NULL,
    description          VARCHAR(2000)  NOT NULL,
    estimated_amount     NUMERIC(15, 2) NOT NULL,
    reserve_amount       NUMERIC(15, 2) NOT NULL,
    status               VARCHAR(20)    NOT NULL,
    assigned_officer_id  VARCHAR(20)    REFERENCES app_user (id),
    created_at           TIMESTAMPTZ    NOT NULL,
    updated_at           TIMESTAMPTZ    NOT NULL,
    version              BIGINT         NOT NULL DEFAULT 0,  -- optimistic locking
    CONSTRAINT uq_claim_claim_number UNIQUE (claim_number),
    CONSTRAINT chk_claim_type CHECK (type IN ('MOTOR', 'PROPERTY')),
    CONSTRAINT chk_claim_status CHECK (status IN
        ('SUBMITTED', 'UNDER_REVIEW', 'INFO_REQUESTED', 'APPROVED', 'SETTLED', 'REJECTED')),
    CONSTRAINT chk_claim_estimated_amount CHECK (estimated_amount >= 0),
    CONSTRAINT chk_claim_reserve_amount CHECK (reserve_amount >= 0),
    CONSTRAINT chk_claim_market_currency CHECK ((market, currency) IN (
        ('SG', 'SGD'), ('MY', 'MYR'), ('HK', 'HKD'), ('TH', 'THB'), ('ID', 'IDR'), ('AU', 'AUD')))
);

CREATE INDEX idx_claim_status ON claim (status);
CREATE INDEX idx_claim_assigned_officer_id ON claim (assigned_officer_id);
CREATE INDEX idx_claim_policy_id ON claim (policy_id);

-- Audit trail: one row per status change. from_status is NULL for the initial SUBMITTED entry.
CREATE TABLE claim_status_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id     BIGINT       NOT NULL REFERENCES claim (id),
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    changed_by   VARCHAR(20)  NOT NULL REFERENCES app_user (id),
    reason       VARCHAR(500),
    changed_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT chk_history_from_status CHECK (from_status IN
        ('SUBMITTED', 'UNDER_REVIEW', 'INFO_REQUESTED', 'APPROVED', 'SETTLED', 'REJECTED')),
    CONSTRAINT chk_history_to_status CHECK (to_status IN
        ('SUBMITTED', 'UNDER_REVIEW', 'INFO_REQUESTED', 'APPROVED', 'SETTLED', 'REJECTED'))
);

CREATE INDEX idx_claim_status_history_claim_id ON claim_status_history (claim_id);

CREATE TABLE information_request (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id      BIGINT        NOT NULL REFERENCES claim (id),
    question      VARCHAR(2000) NOT NULL,
    response      VARCHAR(2000),
    requested_by  VARCHAR(20)   NOT NULL REFERENCES app_user (id),
    requested_at  TIMESTAMPTZ   NOT NULL,
    responded_at  TIMESTAMPTZ,
    -- A response and its timestamp are recorded together.
    CONSTRAINT chk_information_request_response CHECK (
        (response IS NULL AND responded_at IS NULL) OR (response IS NOT NULL AND responded_at IS NOT NULL))
);

CREATE INDEX idx_information_request_claim_id ON information_request (claim_id);
