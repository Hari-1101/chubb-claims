-- V3: reserve audit, notifications, consumer idempotency and the reporting read model.

-- claim module: audit trail of reserve changes (who, why, from/to).
CREATE TABLE reserve_change (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    BIGINT         NOT NULL REFERENCES claim (id),
    old_amount  NUMERIC(15, 2) NOT NULL,
    new_amount  NUMERIC(15, 2) NOT NULL,
    changed_by  VARCHAR(20)    NOT NULL REFERENCES app_user (id),
    reason      VARCHAR(500)   NOT NULL,
    changed_at  TIMESTAMPTZ    NOT NULL,
    CONSTRAINT chk_reserve_change_old_amount CHECK (old_amount >= 0),
    CONSTRAINT chk_reserve_change_new_amount CHECK (new_amount >= 0)
);

CREATE INDEX idx_reserve_change_claim_id ON reserve_change (claim_id);

-- notification module: messages for claimants, written by the Kafka consumer.
-- claim_number (not a FK to claim) on purpose: the module only knows what the events tell it.
CREATE TABLE notification (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id     VARCHAR(20)  NOT NULL REFERENCES app_user (id),
    recipient_email  VARCHAR(255) NOT NULL,
    claim_number     VARCHAR(30)  NOT NULL,
    message          VARCHAR(500) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_notification_recipient_created ON notification (recipient_id, created_at DESC);

-- Consumer idempotency: one row per (event, consumer group), inserted in the same transaction as the consumer's work.
CREATE TABLE processed_event (
    event_id        UUID        NOT NULL,
    consumer_group  VARCHAR(50) NOT NULL,
    processed_at    TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (event_id, consumer_group)
);

-- reporting module: read model built only from events (no FKs to the claim tables, on purpose).
CREATE TABLE reporting_claim (
    claim_number         VARCHAR(30)    PRIMARY KEY,
    status               VARCHAR(20)    NOT NULL,
    market               VARCHAR(2)     NOT NULL,
    currency             VARCHAR(3)     NOT NULL,
    type                 VARCHAR(20)    NOT NULL,
    reserve_amount       NUMERIC(15, 2) NOT NULL,
    assigned_officer_id  VARCHAR(20),
    submitted_at         TIMESTAMPTZ    NOT NULL,
    decided_at           TIMESTAMPTZ,
    last_claim_version   BIGINT         NOT NULL,
    updated_at           TIMESTAMPTZ    NOT NULL   -- when this row last changed (freshness of the read model)
);

CREATE INDEX idx_reporting_claim_status ON reporting_claim (status);
CREATE INDEX idx_reporting_claim_assigned_officer_id ON reporting_claim (assigned_officer_id);
CREATE INDEX idx_reporting_claim_decided_at ON reporting_claim (decided_at);
